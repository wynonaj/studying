from __future__ import annotations

from collections.abc import Sequence


def _topic(
    section: int,
    title: str,
    q: str,
    correct: str,
    distractors: Sequence[str],
    teach: str,
    answer: str,
    example: str,
    source_label: str,
    slides: Sequence[int] = (),
) -> dict:
    """Build one normalized guide-topic record."""

    return {
        "section": section,
        "title": title,
        "q": q,
        "correct": correct,
        "distractors": list(distractors),
        "teach": teach,
        "answer": answer,
        "example": example,
        "sourceLabel": source_label,
        "slides": list(slides),
    }


def _exercise(
    number: int,
    q: str,
    correct: str,
    options: Sequence[str],
    teach: str,
    answer: str,
    example: str,
) -> dict:
    """Build one normalized exercise record and retain all source choices."""

    choices = list(options)
    return {
        "exerciseNumber": number,
        "section": 5,
        "q": q,
        "correct": correct,
        "options": choices,
        "distractors": [choice for choice in choices if choice != correct],
        "teach": teach,
        "answer": answer,
        "example": example,
    }


